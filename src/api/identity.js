/**
 * 身份标识 —— 全项目唯一「我是谁」的出处
 *
 * 为什么需要它：订阅数据必须有个归属，否则后端不知道某条订阅该算给谁。
 *
 * 当前策略：单用户模式（项目还没有登录体系）。
 *   所有请求都带同一个固定 ID，相当于把整个系统都记在唯一用户（owner）名下。
 *   为什么不按浏览器各生成一个 UUID（原 deviceId 方案）：那样换设备 / 清缓存
 *   就看不到自己的订阅；固定 ID 则任何设备打开都是同一份数据。
 *   代价（明确接受）：谁打开这个网址都能看到这些订阅 —— 对个人自用工具无影响。
 *
 * ★ 将来接入登录时，只改本文件：
 *     把 getIdentityId() 里 return 常量那一行，换成「从登录态取当前用户 id」。
 *   拦截器、接口、数据表、store、页面一行都不用动 —— 因为「身份」在这里被收敛成一个点。
 */

/** 单用户模式下的固定身份 ID。将来接登录后此常量作废（那时每人有自己的 id） */
const SINGLE_OWNER_ID = 'owner';

/**
 * 取当前请求的身份标识。
 * 现在：永远返回同一个常量。
 * 将来：改成从登录态读取，函数名与签名都不变，调用方无感。
 */
export function getIdentityId() {
  // ⬇⬇ 接入登录时只改这一行，例如：return authStore.userId ?? 'guest';
  return SINGLE_OWNER_ID;
}
